-- POSTGRESQL
USE HOSPITAL_LAB_DB;

CREATE TABLE IF NOT EXISTS "PHOTOS" (
    PHOTO_ID BIGSERIAL PRIMARY KEY,
    PHOTO_UUID VARCHAR(36) DEFAULT (gen_random_uuid()) UNIQUE,
    PHOTO_IS_VISIBLE BOOLEAN DEFAULT TRUE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Index
CREATE INDEX IF NOT EXISTS PHOTO_UUID_INDEX ON "PHOTOS" (PHOTO_UUID);


-- Stored Procedure
-- Insert Photo
```
CREATE OR REPLACE FUNCTION INSERT_NEW_PHOTO(
    IN P_PHOTO_UUID VARCHAR(36),
    OUT P_SUCCESS BOOLEAN
)
AS $$
DECLARE
    NEW_PHOTO_UUID VARCHAR(36);
BEGIN
    -- CREATE NEW PHOTO
    BEGIN
        INSERT INTO "PHOTOS" (
            PHOTO_UUID
        ) VALUES (
            P_PHOTO_UUID
        )
        RETURNING PHOTO_UUID INTO NEW_PHOTO_UUID;
        
        P_SUCCESS := TRUE;
    EXCEPTION
        WHEN OTHERS THEN
            P_SUCCESS := FALSE;
    END;
END;